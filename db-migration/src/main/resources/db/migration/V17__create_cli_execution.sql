CREATE TABLE IF NOT EXISTS tbl_cli_execution (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id VARCHAR(255) NOT NULL,
    script TEXT NOT NULL,
    environment JSONB NOT NULL DEFAULT '{}'::jsonb,
    exit_code INTEGER NOT NULL,
    stdout TEXT NOT NULL,
    stderr TEXT NOT NULL,
    duration_ms BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL,
    executed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    creator VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by VARCHAR(255) NOT NULL,
    CONSTRAINT chk_tbl_cli_execution_status CHECK (
        status IN ('COMPLETED', 'TIMED_OUT', 'FAILED_TO_START')
    )
);

CREATE INDEX IF NOT EXISTS idx_tbl_cli_execution_owner_executed_at
    ON tbl_cli_execution (owner_user_id, executed_at DESC);

CREATE INDEX IF NOT EXISTS idx_tbl_cli_execution_executed_at
    ON tbl_cli_execution (executed_at DESC);

COMMENT ON TABLE tbl_cli_execution IS
    'Audit log of authenticated CLI / shell executions and their results.';
COMMENT ON COLUMN tbl_cli_execution.id IS 'Persistent CLI execution audit identifier (bigint identity)';
COMMENT ON COLUMN tbl_cli_execution.owner_user_id IS
    'OIDC subject of the authenticated user that ran the command';
COMMENT ON COLUMN tbl_cli_execution.script IS 'Shell script or command submitted by the caller';
COMMENT ON COLUMN tbl_cli_execution.environment IS
    'Environment variables supplied with the execution, stored as a JSON object';
COMMENT ON COLUMN tbl_cli_execution.exit_code IS
    'Process exit code, or -1 when unavailable (for example timed out or failed to start)';
COMMENT ON COLUMN tbl_cli_execution.stdout IS 'Captured standard output (possibly truncated)';
COMMENT ON COLUMN tbl_cli_execution.stderr IS 'Captured standard error (possibly truncated)';
COMMENT ON COLUMN tbl_cli_execution.duration_ms IS 'Wall-clock duration of the execution in milliseconds';
COMMENT ON COLUMN tbl_cli_execution.status IS
    'Execution outcome: COMPLETED, TIMED_OUT, or FAILED_TO_START';
COMMENT ON COLUMN tbl_cli_execution.executed_at IS 'Instant when the execution started';
COMMENT ON COLUMN tbl_cli_execution.creator IS 'Identifier of the actor that created the audit row';
COMMENT ON COLUMN tbl_cli_execution.created_at IS 'Audit row creation timestamp';
COMMENT ON COLUMN tbl_cli_execution.updated_at IS 'Audit row last update timestamp';
COMMENT ON COLUMN tbl_cli_execution.updated_by IS 'Identifier of the actor that last updated the audit row';
