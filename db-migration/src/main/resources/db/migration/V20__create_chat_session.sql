CREATE TABLE IF NOT EXISTS tbl_chat_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    thread_id VARCHAR(200) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_tbl_chat_session_thread_id UNIQUE (thread_id)
);

CREATE INDEX IF NOT EXISTS idx_tbl_chat_session_owner_updated
    ON tbl_chat_session (owner_user_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS tbl_chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    role VARCHAR(32) NOT NULL,
    content TEXT NOT NULL,
    plan TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_tbl_chat_message_session
        FOREIGN KEY (session_id) REFERENCES tbl_chat_session (id) ON DELETE CASCADE,
    CONSTRAINT chk_tbl_chat_message_role CHECK (role IN ('user', 'assistant', 'system'))
);

CREATE INDEX IF NOT EXISTS idx_tbl_chat_message_session_created
    ON tbl_chat_message (session_id, created_at);

COMMENT ON TABLE tbl_chat_session IS 'User-owned chat sessions for AgentGo conversations';
COMMENT ON TABLE tbl_chat_message IS 'Persisted chat turns for a session';
