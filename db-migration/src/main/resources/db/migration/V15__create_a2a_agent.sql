CREATE TABLE IF NOT EXISTS tbl_a2a_agent (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id VARCHAR(255) NOT NULL,
    card_url VARCHAR(2048) NOT NULL,
    group_name VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(4000),
    tags JSONB NOT NULL DEFAULT '[]'::jsonb,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    description_vector JSONB NOT NULL DEFAULT '[]'::jsonb,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    status VARCHAR(32) NOT NULL DEFAULT 'UNKNOWN',
    creator VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by VARCHAR(255) NOT NULL,
    CONSTRAINT uq_tbl_a2a_agent_group_name_name_creator UNIQUE (group_name, name, creator),
    CONSTRAINT chk_tbl_a2a_agent_status CHECK (
        status IN ('UNKNOWN', 'AVAILABLE', 'UNAVAILABLE', 'ERROR')
    )
);

CREATE INDEX IF NOT EXISTS idx_tbl_a2a_agent_owner_status
    ON tbl_a2a_agent (owner_user_id, status);

CREATE INDEX IF NOT EXISTS idx_tbl_a2a_agent_owner_enabled
    ON tbl_a2a_agent (owner_user_id, enabled);

COMMENT ON TABLE tbl_a2a_agent IS
    'User-owned A2A sub-agents addressed by an Agent Card URL';
COMMENT ON COLUMN tbl_a2a_agent.id IS 'Persistent A2A agent identifier (bigint identity)';
COMMENT ON COLUMN tbl_a2a_agent.owner_user_id IS
    'Authenticated owner resolved from the security context';
COMMENT ON COLUMN tbl_a2a_agent.card_url IS
    'Absolute HTTP(S) URL of the remote A2A Agent Card';
COMMENT ON COLUMN tbl_a2a_agent.group_name IS 'Group name unique together with name and creator';
COMMENT ON COLUMN tbl_a2a_agent.name IS 'Human-readable display name unique with group name and creator';
COMMENT ON COLUMN tbl_a2a_agent.description IS 'Optional free-form description used to build the description vector';
COMMENT ON COLUMN tbl_a2a_agent.tags IS 'Display tags stored as a JSON array of strings';
COMMENT ON COLUMN tbl_a2a_agent.metadata IS 'Caller-defined JSON object metadata';
COMMENT ON COLUMN tbl_a2a_agent.description_vector IS
    '64-dimension L2-normalized feature hash of the description, stored as a JSON array of numbers';
COMMENT ON COLUMN tbl_a2a_agent.enabled IS
    'Whether the agent is available for Agent runtime assembly';
COMMENT ON COLUMN tbl_a2a_agent.status IS
    'Operator status: UNKNOWN, AVAILABLE, UNAVAILABLE, or ERROR';
COMMENT ON COLUMN tbl_a2a_agent.creator IS 'Identifier of the actor that created the row';
COMMENT ON COLUMN tbl_a2a_agent.created_at IS 'Row creation timestamp';
COMMENT ON COLUMN tbl_a2a_agent.updated_at IS 'Row last update timestamp';
COMMENT ON COLUMN tbl_a2a_agent.updated_by IS 'Identifier of the actor that last updated the row';
