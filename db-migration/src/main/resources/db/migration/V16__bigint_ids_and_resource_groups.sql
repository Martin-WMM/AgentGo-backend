-- Replace application UUID primary keys with bigint identity values.
-- Authentik user UUIDs stay UUID because they are identifiers owned by Authentik.
-- Existing rows receive new sequential ids. Prompt revision foreign keys are remapped
-- before the old template id column is removed.

ALTER TABLE tbl_prompt_template
    ADD COLUMN id_new BIGINT GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE tbl_prompt_template_revision
    DROP CONSTRAINT IF EXISTS fk_tbl_prompt_template_revision_template;

ALTER TABLE tbl_prompt_template_revision
    DROP CONSTRAINT IF EXISTS uq_tbl_prompt_template_revision_template_revision;

ALTER TABLE tbl_prompt_template_revision
    ADD COLUMN template_id_new BIGINT;

UPDATE tbl_prompt_template_revision AS revision
SET template_id_new = template.id_new
FROM tbl_prompt_template AS template
WHERE revision.template_id = template.id;

ALTER TABLE tbl_prompt_template DROP CONSTRAINT tbl_prompt_template_pkey;
ALTER TABLE tbl_prompt_template DROP COLUMN id;
ALTER TABLE tbl_prompt_template RENAME COLUMN id_new TO id;
ALTER TABLE tbl_prompt_template ADD PRIMARY KEY (id);

DROP INDEX IF EXISTS idx_tbl_prompt_template_revision_template_id;

ALTER TABLE tbl_prompt_template_revision DROP COLUMN template_id;
ALTER TABLE tbl_prompt_template_revision RENAME COLUMN template_id_new TO template_id;
ALTER TABLE tbl_prompt_template_revision ALTER COLUMN template_id SET NOT NULL;

ALTER TABLE tbl_prompt_template_revision
    ADD CONSTRAINT uq_tbl_prompt_template_revision_template_revision
        UNIQUE (template_id, revision_number);

ALTER TABLE tbl_prompt_template_revision
    ADD CONSTRAINT fk_tbl_prompt_template_revision_template
        FOREIGN KEY (template_id) REFERENCES tbl_prompt_template (id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_tbl_prompt_template_revision_template_id
    ON tbl_prompt_template_revision (template_id, revision_number DESC);

ALTER TABLE tbl_prompt_template_revision ADD COLUMN id_new BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE tbl_prompt_template_revision DROP CONSTRAINT tbl_prompt_template_revision_pkey;
ALTER TABLE tbl_prompt_template_revision DROP COLUMN id;
ALTER TABLE tbl_prompt_template_revision RENAME COLUMN id_new TO id;
ALTER TABLE tbl_prompt_template_revision ADD PRIMARY KEY (id);

COMMENT ON COLUMN tbl_prompt_template.id IS 'Persistent prompt template identifier (bigint identity)';
COMMENT ON COLUMN tbl_prompt_template_revision.id IS 'Persistent revision identifier (bigint identity)';
COMMENT ON COLUMN tbl_prompt_template_revision.template_id IS 'Owning prompt template identifier';

-- Tables whose primary key is not referenced by another AgentGo table.
DO $$
DECLARE
    target_table text;
BEGIN
    FOREACH target_table IN ARRAY '{tbl_file,tbl_model,tbl_workspace,tbl_user_profile,tbl_user_settings,tbl_mcp_server,tbl_system_event}'::text[]
    LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN id_new BIGINT GENERATED BY DEFAULT AS IDENTITY', target_table);
        EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I', target_table, target_table || '_pkey');
        EXECUTE format('ALTER TABLE %I DROP COLUMN id', target_table);
        EXECUTE format('ALTER TABLE %I RENAME COLUMN id_new TO id', target_table);
        EXECUTE format('ALTER TABLE %I ADD PRIMARY KEY (id)', target_table);
        EXECUTE format(
            'COMMENT ON COLUMN %I.id IS %L',
            target_table,
            'Persistent identifier (bigint identity)'
        );
    END LOOP;
END $$;

